<div class="content-box">
    <p>
        Elective 1 – Web Systems and Technologies is a course that introduces students
        to the fundamental and advanced concepts of modern web application development.
        It focuses on the design, implementation, and deployment of interactive,
        database-driven, and responsive web systems using current technologies and frameworks.
    </p>

    <p>
        The course covers both client-side and server-side development, including
        HTML, CSS, JavaScript, PHP, and Laravel Framework. It also emphasizes the use of
        web standards, security practices, and integration of databases for building
        real-world web-based information systems.
    </p>

    <p>
        By the end of the course, students will be able to develop functional,
        secure, and user-friendly web applications that follow industry best practices
        and support modern business and organizational needs.
    </p>
